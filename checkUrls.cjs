async function checkUrl(id) {
  return new Promise((resolve) => {
    https.get(`https://images.unsplash.com/photo-${id}?w=640&h=360&fit=crop`, (res) => {
      resolve({ id, status: res.statusCode });
    }).on('error', (e) => {
      resolve({ id, status: 500 });
    });
  });
}

async function run() {
  const results = await Promise.all(urls.map(checkUrl));
  const broken = results.filter(r => r.status !== 200 && r.status !== 302);
  console.log('Broken URLs:', broken);
}

run();
